/**
 * Жёсткая защита клиентского AI: жалобы на сроки и запросы против компании
 * не уходят в модель — возвращается безопасный ответ.
 */

/** Вопросы про ожидание, сроки, «почему так долго», «сколько ждать». */
const WAIT_TIME_PATTERNS = [
  /почему\s+так\s+долг/i,
  /почему\s+(вс[её]|все)\s+так\s+долг/i,
  /почему\s+долг/i,
  /сколько\s+(ещё|еще|времени)?\s*ждать/i,
  /сколько\s+ждать/i,
  /как\s+долго\s+(ждать|ожидать)/i,
  /долго\s+(ждать|ожидать|нет\s+новост)/i,
  /когда\s+(будет|ждать|ожидать|прид[её]т)\s*(ответ|решени|новост|статус)?/i,
  /когда\s+уже/i,
  /срок(и|ов|а)?\s+(рассмотрен|ожидан|обработк|внж|виз)/i,
  /срок(и|ов)?\s+(очень\s+)?долг/i,
  /долг(ие|ий|ое|ая)?\s+срок/i,
  /нет\s+(новост|сообщени|обновлен|ответ)/i,
  /долг(о|ое|ий|ая)\s+(ждёт|ждет|ожидан|тишин)/i,
  /прошло\s+\d+/i,
  /\d+\s*(месяц|мес\.?|недел).*(ждать|тишин|новост|обновлен|нет|помогите|что\s+делать)/i,
  /(ждать|тишин|новост|обновлен|нет|помогите|что\s+делать).*\d+\s*(месяц|мес\.?|недел)/i,
  /подач[аие].*(последн|обновлен|тишин|сообщени)/i,
  /последн\w*\s+обновлен/i,
  /после\s+никаких/i,
  /тишин(а|ы|е)/i,
  /задержк/i,
  /почему\s+нет\s+(ответ|новост|сообщени)/i,
  /что\s+делать.*(ждать|тишин|месяц|срок)/i,
  /(ждать|ожидан).*(что\s+делать|помогите|долго|срок)/i,
  /ожидан(ие|ия|ии).*(долг|срок|месяц)/i,
  /временн(ые|ых|ые)\s+рамк/i,
  /анализ\s+времен/i,
];

const AGAINST_COMPANY_PATTERNS = [
  /суд(ить|иться|ебн)?/i,
  /в\s+суд/i,
  /иск\b/i,
  /претензи/i,
  /жалоб(а|у|ы)\s+(на\s+)?(компани|эмигрант|emigrant)/i,
  /против\s+(компани|эмигрант|emigrant|вас)/i,
  /верните\s+деньг/i,
  /возврат\s+денег/i,
  /обманули/i,
  /мошенн/i,
  /требу(ю|йте|ем)\s+(от\s+)?(компани|эмигрант)/i,
  /пода(ть|вайте)\s+в\s+суд/i,
  /юрист.*(против|на\s+компани)/i,
  /адвокат.*(против|на\s+компани)/i,
  /не\s+делает\s+ничего/i,
  /виноват[аы]?\s+(компани|эмигрант)/i,
];

export function shouldUseCompanySafeReply(message: string): boolean {
  const text = message.trim();
  if (!text) {
    return false;
  }

  if (AGAINST_COMPANY_PATTERNS.some((pattern) => pattern.test(text))) {
    return true;
  }

  // Любой вопрос про сроки / ожидание / «почему так долго» — фиксированный ответ.
  if (WAIT_TIME_PATTERNS.some((pattern) => pattern.test(text))) {
    return true;
  }

  return false;
}
